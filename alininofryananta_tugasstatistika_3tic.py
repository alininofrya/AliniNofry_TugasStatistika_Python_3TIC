import pandas as pd

df = pd.read_excel('alini.xlsx')

df

frekuensi = df['Grade'].value_counts()
frekuensi

urutan_grade = ['A', 'AB', 'B', 'BC', 'C', 'D']

frekuensi = df['Grade'].value_counts().reindex(urutan_grade)
frekuensi

import matplotlib.pyplot as plt

plt.figure(figsize=(8,5))

plt.plot(frekuensi.index, frekuensi.values, marker='o', linewidth=2)

for x, y in zip(frekuensi.index, frekuensi.values):
    plt.text(x, y + 0.3, str(y), ha='center')

plt.title('Distribusi Frekuensi Grade Mahasiswa')
plt.xlabel('Grade')
plt.ylabel('Jumlah Mahasiswa')

plt.grid(True, linestyle='--', alpha=0.4)
plt.show()

plt.figure(figsize=(8,5))

plt.bar(frekuensi.index, frekuensi.values)

