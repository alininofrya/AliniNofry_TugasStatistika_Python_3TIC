statistik = df['Final Score'].describe()
statistik

mean = df['Final Score'].mean()
median = df['Final Score'].median()
modus = df['Final Score'].mode()

print("Mean   :", mean)
print("Median :", median)
print("Modus  :", modus.tolist())

minimum = df['Final Score'].min()
maksimum = df['Final Score'].max()
rentang = maksimum - minimum

print("Minimum :", minimum)
print("Maximum :", maksimum)
print("Range   :", rentang)

q1 = df['Final Score'].quantile(0.25)
q2 = df['Final Score'].quantile(0.50)
q3 = df['Final Score'].quantile(0.75)

print("Q1 :", q1)
